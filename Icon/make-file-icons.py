#!/usr/bin/env python3
"""Embed the hand-drawn file-type icon set as Swift source.

Reads both halves of the set from this repo — `file-icon/icons/*.svg` (the
outline badge) and `file-icon/icons-filled/*.svg` (the same badge solid) —
and writes `Sources/Nota/FileKindArt.swift`: two `[String: String]` maps of
SVG text keyed by file stem (the extension each icon was drawn for), as Swift
multi-line raw string literals so nothing needs escaping.

The art is exported with 15-digit coordinates, which would put well over a
megabyte of decimal places into the binary for no visible difference. Every
number is therefore shortened on the way through: two decimals for anything
at or above 1 (a hundredth of a unit in a 96×64 badge is far under a pixel at
any size Nota draws these), six significant digits below it — the glyph
groups carry a `scale(0.018018 …)` that two decimals would destroy.

Run from anywhere:

    python3 Icon/make-file-icons.py

Nothing else consumes this script's output at build time — `FileKindArt.swift`
is committed source, regenerated by hand whenever the art changes.
"""
import re
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
ART_DIR = REPO_ROOT / "file-icon"
OUTLINE_DIR = ART_DIR / "icons"
FILLED_DIR = ART_DIR / "icons-filled"
OUTPUT = REPO_ROOT / "Sources" / "Nota" / "FileKindArt.swift"

HEADER = '''\
// GENERATED FILE — do not edit by hand.
//
// Produced by `Icon/make-file-icons.py` from the file-type icon set drawn in
// this repo under `file-icon/` — a 96×64 rounded badge with the extension
// lettered inside it, `icons/` outlined and `icons-filled/` solid, both in
// `currentColor` so either can be loaded as an NSImage template and tinted
// like an SF Symbol. Every coordinate has been shortened by the script; see
// its docstring. Rerun it after the art changes; nothing here is meant to be
// hand-edited.

/// The file-kind icon set, embedded as raw SVG text keyed by file stem
/// (e.g. "md", "pdf" — the extension the icon was drawn for, plus "untitled"
/// for a note that has no name yet and "unknown" for a kind nobody drew).
/// Two drawings of every stem: `outline` for an ordinary tab, `filled` for a
/// bookmarked one. See `FileKindIcon.image(named:pointSize:filled:)`.
enum FileKindArt {
'''

FOOTER = '''\
}
'''

NUMBER = re.compile(r"-?\d+\.\d+")


def shorten(match: "re.Match[str]") -> str:
    """One number, with the decimal places nobody can see taken off."""
    value = float(match.group(0))
    text = f"{value:.2f}" if abs(value) >= 1 else f"{value:.6g}"
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text or "0"


def swift_raw_string(text: str) -> str:
    # A Swift multi-line raw string literal, hash-delimited, holding `text`
    # verbatim. The closing delimiter sits at column 0 so Swift's
    # common-indentation stripping never touches the content.
    body = NUMBER.sub(shorten, text).rstrip("\n")
    quote = '"' * 3
    return f'#{quote}\n{body}\n{quote}#'


def table(name: str, directory: Path, doc: str) -> str:
    paths = sorted(directory.glob("*.svg"))
    if not paths:
        raise SystemExit(f"no .svg files found under {directory}")
    lines = [f"    /// {doc}", f"    static let {name}: [String: String] = ["]
    for path in paths:
        lines.append(f'        "{path.stem}": {swift_raw_string(path.read_text(encoding="utf-8"))},')
    lines.append("    ]")
    return "\n".join(lines), len(paths)


def main() -> None:
    outline, outline_count = table(
        "outline", OUTLINE_DIR, "The ordinary badge: the extension inside a hollow rounded rect."
    )
    filled, filled_count = table(
        "filled", FILLED_DIR, "The same badge solid, which is how a bookmarked tab draws."
    )
    if outline_count != filled_count:
        raise SystemExit(
            f"the two halves disagree: {outline_count} outline, {filled_count} filled"
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(HEADER + outline + "\n\n" + filled + "\n" + FOOTER, encoding="utf-8")
    print(f"wrote {OUTPUT} ({outline_count} icons × 2 from {ART_DIR})")


if __name__ == "__main__":
    main()
