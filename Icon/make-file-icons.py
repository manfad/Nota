#!/usr/bin/env python3
"""Embed the hand-drawn file-type icon set as Swift source.

Reads every SVG in the sibling `favcon` repo's `svg/cropped` directory and
writes `Sources/Nota/FileKindArt.swift`: a `[String: String]` of SVG text
keyed by file stem (the extension each icon was drawn for), as Swift
multi-line raw string literals so nothing needs escaping.

Run from anywhere:

    python3 Icon/make-file-icons.py

Nothing else consumes this script's output at build time — `FileKindArt.swift`
is committed source, regenerated by hand whenever the art changes.
"""
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
SVG_DIR = REPO_ROOT.parent / "favcon" / "svg" / "cropped"
OUTPUT = REPO_ROOT / "Sources" / "Nota" / "FileKindArt.swift"

HEADER = '''\
// GENERATED FILE — do not edit by hand.
//
// Produced by `Icon/make-file-icons.py` from the hand-drawn file-type icon
// set in the sibling `favcon` repo (`favcon/svg/cropped/*.svg`) — Apple's
// SF Symbol `doc` outline with the extension lettered under it, drawn in
// `currentColor` so it can be loaded as an NSImage template and tinted like
// an SF Symbol. Rerun the script after the art changes; nothing here is
// meant to be hand-edited.

/// The custom file-kind icon set, embedded as raw SVG text keyed by file
/// stem (e.g. "md", "pdf" — the extension the icon was drawn for). See
/// `FileKindIcon.image(named:pointSize:)` for how these are drawn.
enum FileKindArt {
    static let svg: [String: String] = [
'''

FOOTER = '''\
    ]
}
'''


def swift_raw_string(text: str) -> str:
    # A Swift multi-line raw string literal, hash-delimited, holding `text`
    # verbatim. The closing delimiter sits at column 0 so Swift's
    # common-indentation stripping never touches the content.
    body = text.rstrip("\n")
    quote = '"' * 3
    return f'#{quote}\n{body}\n{quote}#'


def main() -> None:
    svg_paths = sorted(SVG_DIR.glob("*.svg"))
    if not svg_paths:
        raise SystemExit(f"no .svg files found under {SVG_DIR}")

    entries = []
    for path in svg_paths:
        stem = path.stem
        text = path.read_text(encoding="utf-8")
        entries.append(f'        "{stem}": {swift_raw_string(text)},')

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(HEADER + "\n".join(entries) + "\n" + FOOTER, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(svg_paths)} icons from {SVG_DIR})")


if __name__ == "__main__":
    main()
