/// Small, runtime-switchable interface vocabulary. Nota is built without a
/// nib or asset catalogue, so keeping these strings here lets the language
/// setting take effect immediately instead of requiring a relaunch.
///
/// One table per language, all keyed by the English string, so a call site
/// reads as English and every table is checked against the same key set by
/// `LocalizationTests`. `.system` is resolved to a real language by
/// `AppLanguage.resolved` before a table is picked.
enum L10n {
    static func text(_ english: String, chinese: String? = nil) -> String {
        switch Preferences.shared.language.resolved {
        case .simplifiedChinese: return chinese ?? simplifiedChinese[english] ?? english
        case .traditionalChinese: return traditionalChinese[english] ?? english
        case .malay: return malay[english] ?? english
        default: return english
        }
    }

    /// The table a language reads from, `nil` for English. Only the tests
    /// need this; the app calls `text(_:chinese:)`.
    static func table(for language: AppLanguage) -> [String: String]? {
        switch language.resolved {
        case .simplifiedChinese: simplifiedChinese
        case .traditionalChinese: traditionalChinese
        case .malay: malay
        default: nil
        }
    }

