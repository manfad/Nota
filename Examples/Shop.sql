-- Shop.sql — a small shop, as a dump.
--
-- Four tables that know about each other: customers place orders, orders
-- hold items, and items name products. Enough rows that the grid pages.

PRAGMA foreign_keys = ON;

CREATE TABLE customers (
    id       INTEGER PRIMARY KEY,
    name     TEXT NOT NULL,
    city     TEXT,
    email    TEXT,
    joined   TEXT NOT NULL
);

CREATE TABLE products (
    id        INTEGER PRIMARY KEY,
    name      TEXT NOT NULL,
    category  TEXT NOT NULL,
    price     REAL NOT NULL,
    in_stock  INTEGER NOT NULL,
    thumbnail BLOB
);

CREATE TABLE orders (
    id          INTEGER PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(id),
    placed      TEXT NOT NULL,
    status      TEXT NOT NULL,
    note        TEXT
);

CREATE TABLE order_items (
    id         INTEGER PRIMARY KEY,
    order_id   INTEGER NOT NULL REFERENCES orders(id),
    product_id INTEGER NOT NULL REFERENCES products(id),
    quantity   INTEGER NOT NULL,
    unit_price REAL NOT NULL
);

CREATE INDEX orders_by_customer ON orders(customer_id);
CREATE INDEX items_by_order ON order_items(order_id);

